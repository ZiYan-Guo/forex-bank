CREATE TABLE IF NOT EXISTS t_month_end_closing (
    id BIGINT NOT NULL,
    closing_id VARCHAR(64) NOT NULL,
    fiscal_period VARCHAR(10) NOT NULL,
    closing_date DATE NOT NULL,
    closing_status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',
    checklist_json TEXT,
    audit_trail TEXT,
    total_debits DECIMAL(22,6) DEFAULT 0,
    total_credits DECIMAL(22,6) DEFAULT 0,
    operator_id BIGINT,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME,
    version INT NOT NULL DEFAULT 0,
    deleted TINYINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_closing_id (closing_id),
    KEY idx_fiscal_period (fiscal_period),
    KEY idx_closing_status (closing_status)
);

CREATE TABLE IF NOT EXISTS t_journal_entry (
    id BIGINT NOT NULL,
    voucher_no VARCHAR(64) NOT NULL,
    voucher_date DATE NOT NULL,
    fiscal_period VARCHAR(10) NOT NULL,
    biz_type VARCHAR(30) NOT NULL,
    biz_no VARCHAR(64),
    currency VARCHAR(10) NOT NULL,
    amount DECIMAL(22,6) NOT NULL,
    entry_direction VARCHAR(10) NOT NULL,
    account_code VARCHAR(30) NOT NULL,
    account_name VARCHAR(100),
    opposite_account_code VARCHAR(30),
    summary VARCHAR(500),
    entry_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    reversed_voucher_no VARCHAR(64),
    posted_time DATETIME,
    operator_id BIGINT,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME,
    version INT NOT NULL DEFAULT 0,
    deleted TINYINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_voucher_no (voucher_no),
    KEY idx_fiscal_period (fiscal_period),
    KEY idx_entry_status (entry_status),
    KEY idx_biz_type (biz_type)
);
